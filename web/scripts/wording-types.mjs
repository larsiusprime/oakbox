// Writes src/wording/wording.gen.ts, the types of the wording catalog (src/wording/en.json), from its messages (SPEC §6.6).
//   node scripts/wording-types.mjs           write it
//   node scripts/wording-types.mjs --check   fail if it's out of date (CI)
// A message with no arguments is a string. One with arguments is a function of an object of them: plural,
// selectordinal and number arguments are numbers; a select is its cases (`true` → boolean, `null` → or null,
// `other` → any string); a plain {x} is a string or a number. The keys in records.json are lookup tables keyed by
// an id (Record<string, …>). Lists are tuples (a translation keeps their length).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse, TYPE } from "@formatjs/icu-messageformat-parser";

/** Each argument of a message and what it must be: "number", "plain", or a select's case names. */
function argumentsOf(elements, into = new Map()) {
  const note = (name, kind) => {
    const was = into.get(name);
    // A select's cases, then a number, then plain: the strictest use decides.
    if (!was || was === "plain" || (was === "number" && typeof kind !== "string")) into.set(name, kind);
  };
  for (const e of elements) {
    if (e.type === TYPE.argument) note(e.value, "plain");
    else if (e.type === TYPE.number) note(e.value, "number");
    else if (e.type === TYPE.plural) {
      note(e.value, "number");
      for (const o of Object.values(e.options)) argumentsOf(o.value, into);
    } else if (e.type === TYPE.select) {
      note(e.value, Object.keys(e.options));
      for (const o of Object.values(e.options)) argumentsOf(o.value, into);
    } else if (e.type === TYPE.date || e.type === TYPE.time) note(e.value, "date");
  }
  return into;
}

function argumentType(kind) {
  if (kind === "number") return "number";
  if (kind === "plain") return "string | number";
  if (kind === "date") return "Date | number";
  const cases = kind.filter((c) => c !== "other");
  const types = [];
  if (cases.includes("true") || cases.includes("false")) types.push("boolean");
  const named = cases.filter((c) => !["true", "false", "null"].includes(c));
  if (kind.includes("other")) types.push("string", "number");
  else types.push(...named.map((c) => JSON.stringify(c)));
  if (cases.includes("null")) types.push("null");
  return types.join(" | ");
}

const ident = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function typeOf(value, key, indent, records) {
  if (typeof value === "number") return "number";
  if (typeof value === "string") {
    let ast;
    try {
      ast = parse(value, { ignoreTag: true });
    } catch (e) {
      throw new Error(`${key}: not a valid ICU message (${e.message}): ${value}`);
    }
    const args = argumentsOf(ast);
    if (!args.size) return "string";
    const fields = [...args].map(([name, kind]) => `${ident(name)}: ${argumentType(kind)}`);
    return `(a: { ${fields.join("; ")} }) => string`;
  }
  if (Array.isArray(value)) return `[${value.map((v, i) => typeOf(v, `${key}.${i}`, indent, records)).join(", ")}]`;
  const pad = "  ".repeat(indent + 1);
  if (records.has(key)) {
    const kinds = [...new Set(Object.entries(value).map(([k, v]) => typeOf(v, `${key}.${k}`, indent, records)))];
    return `Record<string, ${kinds.length === 1 ? kinds[0] : kinds.map((k) => `(${k})`).join(" | ")}>`;
  }
  const lines = Object.entries(value).map(
    ([k, v]) => `${pad}${ident(k)}: ${typeOf(v, key ? `${key}.${k}` : k, indent + 1, records)};`,
  );
  return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
}

/** A message's TypeScript type: "string", or the function of its arguments. Throws if it isn't valid ICU. */
export const messageType = (source, key = "") => typeOf(source, key, 0, new Set());

export const DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/wording");

/** wording.gen.ts's text for the catalog as it is on disk. */
export function generate(dir = DIR) {
  const catalog = JSON.parse(fs.readFileSync(path.join(dir, "en.json"), "utf8"));
  const records = new Set(JSON.parse(fs.readFileSync(path.join(dir, "records.json"), "utf8")));
  return `// Generated by scripts/wording-types.mjs from en.json: don't edit (npm run wording:types).
export type Wording = ${typeOf(catalog, "", 0, records)};
`;
}

/** Writes wording.gen.ts; true if it changed. */
export function write(dir = DIR) {
  const target = path.join(dir, "wording.gen.ts");
  const text = generate(dir);
  const was = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (was !== text) fs.writeFileSync(target, text);
  return was !== text;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (process.argv.includes("--check")) {
    const target = path.join(DIR, "wording.gen.ts");
    const was = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (was !== generate()) {
      console.error("src/wording/wording.gen.ts is out of date: run npm run wording:types");
      process.exit(1);
    }
  } else write();
}
